"""Multitimer walk-through (decision 121, Swim Opt 2.3). Run: python3 tests/multitimer.py <site url>?mode=local
Marshal sends two 100 m heats and a 50 m heat; the phone times the 100 m heats on the multitimer;
the Recorder gets the times and places. Writes mt-shots/."""
import asyncio, sys, os
from playwright.async_api import async_playwright
URL = sys.argv[1] if len(sys.argv) > 1 else 'http://127.0.0.1:8102/?mode=local'
os.makedirs('mt-shots', exist_ok=True)
os.chdir('mt-shots')
errs, fails = [], []
def check(ok, what):
    print(('ok   ' if ok else 'FAIL ') + what)
    if not ok: fails.append(what)
async def pin(p, code):
    for c in code: await p.click(f'[data-act=key][data-k="{c}"]')
    await p.wait_for_function("A.pin===''&&(!!A.role||A.pinErr)", timeout=20000)
async def main():
  async with async_playwright() as pw:
    b = await pw.chromium.launch()
    ctx = await b.new_context(viewport={'width': 1512, 'height': 982})
    async def mk(name, w=1512, h=982, scheme='light'):
        p = await ctx.new_page()
        await p.set_viewport_size({'width': w, 'height': h})
        await p.emulate_media(color_scheme=scheme)
        p.on('console', lambda m: errs.append((name, m.text)) if m.type == 'error' else None)
        p.on('pageerror', lambda e: errs.append((name, str(e))))
        await p.goto(URL); await p.wait_for_function("!!A.store", timeout=20000)
        return p
    O = await mk('org')
    await pin(O, '9999'); await O.click('[data-act=year][data-v=current]')
    await O.click('[data-job=organiser]')
    await O.click('[data-act=osec][data-v=students]'); await O.click('[data-act=otest]')
    await O.click('[data-act=oimport]'); await O.wait_for_timeout(200)
    M = await mk('mar', 1180, 820)
    await pin(M, '1111')
    await M.click('[data-act=mpick][data-v=free100]'); await M.click('[data-act=mpick][data-v=F]'); await M.click('[data-act=mpick][data-f=g][data-v="13"]')
    await M.click('[data-act=mgo]')
    for _ in range(6): await M.click('.picklist button[data-act=mset]:not([disabled]) >> nth=0')
    await M.click('[data-act=mnext]'); await M.wait_for_timeout(200)
    for _ in range(4): await M.click('.picklist button[data-act=mset]:not([disabled]) >> nth=0')
    await M.click('[data-act=mnew]'); await M.click('[data-act=mconfirm]'); await M.wait_for_timeout(200)

    S = await mk('slips', 390, 844)
    await pin(S, '4444'); await S.wait_for_timeout(200)
    await S.screenshot(path='1-slips.png')
    check(await S.locator('[data-act=mtopen]').count() == 1, "Time Slips shows the Multitimer button")
    await S.click('[data-act=mtopen]'); await S.screenshot(path='2-ready.png')
    filled = await S.evaluate("A.R.races.get(1).filled.map(Number)")
    check(len(filled) == 6, "race 1 has 6 swimmers")
    await S.click('[data-act=mtgo]'); await S.wait_for_timeout(400)
    for i in range(5):
        await S.click('[data-act=mtsplit]'); await S.wait_for_timeout(150)
    await S.screenshot(path='3-running.png')
    check(await S.evaluate("A.mt.splits.length") == 5, "one tap gives one split (no double count)")
    await S.click('[data-act=mtstop]'); await S.wait_for_timeout(100)
    check(await S.locator('.modal h2', has_text='Stop the clock?').count() == 1, "STOP with too few splits asks first")
    await S.screenshot(path='4-stop-ask.png')
    await S.click('[data-act=closemodal]')
    await S.click('[data-act=mtsplit]'); await S.wait_for_timeout(100)
    await S.click('[data-act=mtstop]'); await S.wait_for_timeout(100)
    sp = await S.evaluate("A.mt.splits")
    check(len(sp) == 6 and sp == sorted(sp) and sp[0] > 0, "6 splits in rising order")
    order = [filled[3], filled[1], filled[0], filled[5], filled[2], filled[4]]
    for l in order[:3]: await S.click(f'[data-act=mttap][data-l="{l}"]')
    await S.screenshot(path='5-placing.png', full_page=True)
    await S.click(f'[data-act=mttap][data-l="{order[2]}"]')  # tap a placed lane to remove it
    check(await S.evaluate("A.mt.taps.length") == 2, "tapping a placed lane removes it")
    for l in order[2:]: await S.click(f'[data-act=mttap][data-l="{l}"]')
    await S.screenshot(path='6-placed.png', full_page=True)
    check(await S.locator('[data-act=mtsend]:not([disabled])').count() == 1, "Send is ready once all are placed")
    await S.click('[data-act=mtsend]'); await S.wait_for_timeout(1500)
    await S.screenshot(path='7-sent.png')
    T = await S.evaluate("A.times.r0001")
    F = await S.evaluate("A.finish.r0001")
    check(all(T['lanes'][str(l)]['t'] == sp[i] and T['lanes'][str(l)]['src'] == 'multi' for i, l in enumerate(order)), "each lane got its split time")
    check([g[0] for g in F['order']] == order[:4], "top 4 taps are the places")

    # race 2: 4 swimmers, 5 splits, delete the double tap
    await S.click('[data-act=mtnext]')
    check(await S.evaluate("A.s.race") == 2 and await S.evaluate("A.mt.phase") == 'ready', "Next race opens race 2 ready to START")
    f2 = await S.evaluate("A.R.races.get(2).filled.map(Number)")
    await S.click('[data-act=mtgo]'); await S.wait_for_timeout(300)
    for i in range(5):
        await S.click('[data-act=mtsplit]'); await S.wait_for_timeout(120)
    await S.click('[data-act=mtstop]')
    check(await S.locator('.msg.warn').count() == 1, "5 splits for 4 swimmers warns")
    await S.click('[data-act=mtfix]'); await S.screenshot(path='8-fix.png')
    await S.click('[data-act=mtdel][data-i="2"]')
    await S.fill('#mtadd', '7512x'); await S.click('[data-act=mtaddok]')
    check(await S.locator('.modal', has_text='Only digits').count() + await S.locator('.modal span[style*="--bad"]').count() >= 1, "a bad typed time is refused")
    await S.click('.modal [data-act=closemodal]')
    check(await S.evaluate("A.mt.splits.length") == 4, "Fix splits deletes the double tap")
    for l in f2: await S.click(f'[data-act=mttap][data-l="{l}"]')
    await S.click('[data-act=mtsend]'); await S.wait_for_timeout(1500)
    check(await S.evaluate("A.times.r0002.lanes") and len(await S.evaluate("Object.keys(A.times.r0002.lanes)")) == 4, "race 2 sent with 4 times")

    # back to the 50 m races: the marshal's next number follows on
    await M.click('[data-act=mpick][data-v=back50]'); await M.click('[data-act=mpick][data-v=F]'); await M.click('[data-act=mpick][data-f=g][data-v="14"]')
    await M.click('[data-act=mgo]')
    check(await M.evaluate("A.counter") == 3, "marshal is on race 3 after the two 100 m races")
    for _ in range(3): await M.click('.picklist button[data-act=mset]:not([disabled]) >> nth=0')
    await M.click('[data-act=mnew]'); await M.click('[data-act=mconfirm]'); await M.wait_for_timeout(300)
    await S.click('[data-act=mtnext]'); await S.click('[data-act=mtclose]'); await S.wait_for_timeout(100)
    check(await S.locator('label.cam').count() == 1 and await S.evaluate("A.s.race") == 3, "Back to slip photo shows the camera on race 3")

    R = await mk('rec')
    await pin(R, '3333'); await R.wait_for_timeout(300)
    await R.screenshot(path='9-recorder.png', full_page=True)
    check(await R.locator('.under', has_text='From multitimer').count() == 6, "Recorder shows From multitimer")
    check(await R.locator('[data-act=rslip][disabled]').count() == 1, "View slip photo is grey")
    check(await R.locator('h3', has_text='Multitimer').count() == 1, "Recorder shows the multitimer splits")
    check(await R.locator('.pinkt').count() == 0, "no pink times")

    # reload mid-race keeps the clock, even when an earlier race still has no slip (check 3, finding 1)
    await M.click('[data-act=mpick][data-v=free100]'); await M.click('[data-act=mpick][data-v=F]'); await M.click('[data-act=mpick][data-f=g][data-v="14"]')
    await M.click('[data-act=mgo]')
    for _ in range(3): await M.click('.picklist button[data-act=mset]:not([disabled]) >> nth=0')
    await M.click('[data-act=mnew]'); await M.click('[data-act=mconfirm]'); await M.wait_for_timeout(300)
    await S.click('[data-act=sgoto]'); await S.click('[data-act=pickrace][data-race="4"]')
    await S.click('[data-act=mtopen]'); await S.click('[data-act=mtgo]'); await S.wait_for_timeout(300)
    await S.click('[data-act=mtsplit]')
    await S.reload(); await S.wait_for_load_state('load'); await S.wait_for_function("!!A.store&&A.R&&A.R.races.size>3", timeout=20000); await S.wait_for_timeout(300)
    check(await S.evaluate("A.mt.phase") == 'run' and len(await S.evaluate("A.mt.splits")) == 1, "reload keeps the running clock and splits")
    check(await S.evaluate("slipRace().race") == 4 and await S.locator('[data-act=mtsplit]').count() == 1, "reload comes back on the race being timed (race 4, not race 3)")

    D = await mk('dark', 390, 844, 'dark')
    await D.wait_for_timeout(200)
    await D.screenshot(path='10-dark-running.png', full_page=True)
    sw = await D.evaluate("document.documentElement.scrollWidth")
    check(sw <= 390, f"no sideways scroll on the phone ({sw})")
    small = await D.evaluate("""[...document.querySelectorAll('main button,main label.btn,main input')].filter(e=>{const r=e.getBoundingClientRect();return r.width&&(r.height<48||r.width<48)}).map(e=>e.textContent.trim()||e.id)""")
    check(not small, f"tap targets 48 px or more {small}")
    await b.close()
  print('errors:', errs)
  print('PASSED' if not fails and not errs else f'FAILED: {len(fails)} checks, {len(errs)} errors')
asyncio.run(main())
